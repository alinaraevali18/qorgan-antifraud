def guess_scheme(row) -> str:
    """Какая схема наиболее вероятна — для выбора текста предупреждения."""
    if row.get("remote_access_app"):
        return "remote_access"
    if row.get("loan_issued_24h"):
        return "loan_dictation"
    if row.get("call_active") and row.get("call_from_unknown"):
        return "security_call"
    if row.get("client_amount_24h_to_avg", 0) > 10 and not row.get("call_active"):
        return "fake_invest"
    return "generic"


def mask(account_id: str) -> str:
    """Псевдо-номер счёта для интерфейса (без внутренних меток данных)."""
    if str(account_id).startswith("CASHOUT"):
        return {"CASHOUT_ATM": "Обнал: банкомат", "CASHOUT_CRYPTO": "Обнал: криптообменник",
                "CASHOUT_P2P": "Обнал: P2P"}.get(account_id, "Обнал")
    h = int(hashlib.sha1(str(account_id).encode()).hexdigest(), 16)
    return f"KZ{h % 90 + 10} ···· {h % 9000 + 1000}"
